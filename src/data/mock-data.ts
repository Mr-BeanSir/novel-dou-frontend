// 根据类型返回对应的模拟数据
export function getMockNovels(type: 'recommended' | 'popular' | 'recent', count: number = 8): Novel[] {
  const novels = [...mockNovels];
  
  switch (type) {
    case 'recommended':
      return novels.filter(novel => novel.is_recommended).slice(0, count);
    case 'popular':
      return novels.sort((a, b) => b.view_count - a.view_count).slice(0, count);
    case 'recent':
      return novels.sort((a, b) => 
        new Date(b.last_chapter_at || b.updated_at).getTime() - 
        new Date(a.last_chapter_at || a.updated_at).getTime()
      ).slice(0, count);
    default:
      return novels.slice(0, count);
  }
}
